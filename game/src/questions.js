// 선생님이 바꾼 은행(이 기기에만 저장). 형식은 { "1": [...], ..., "6": [...], "halloween": [...] }
export function loadBank() {
  try {
    const b = JSON.parse(store.get('pumpkin3-bank'));
    if (b && validateBank(b) === '') return b;
  } catch (e) { /* 기본 은행 */ }
  return defaultBank();
}
export function defaultBank() { return JSON.parse(JSON.stringify({ ...GRADES, halloween: HALLOWEEN })); }
export function validateBank(b) {
  for (const k of ['1', '2', '3', '4', '5', '6', 'halloween']) {
    const list = b[k];
    if (!Array.isArray(list) || list.length < 4) return `"${k}" 묶음에 문제가 4개 이상 있어야 해요.`;
    for (const it of list) {
      if (!it || typeof it.q !== 'string' || !it.q.trim()) return `"${k}" 묶음: 문제 글(q)이 비어 있어요.`;
      if (!Array.isArray(it.c) || it.c.length !== 4 || it.c.some(s => typeof s !== 'string' || !s.trim())) return `"${k}" 묶음 "${it.q.slice(0, 12)}…": 보기(c)는 글 4개여야 해요(첫 번째가 정답).`;
    }
  }
  return '';
}

// 문제 글을 단어 경계에서 4조각 낸다: 가능한 모든 자르기 중 가장 긴 조각이 가장 짧은 것을 고른다
export function splitParts(q, n = 4) {
  const words = q.split(/\s+/).filter(Boolean);
  while (words.length < n) {   // 단어가 모자라면 가장 긴 단어를 반으로
    const i = words.reduce((bi, w, k) => (w.length > words[bi].length ? k : bi), 0), w = words[i], h = Math.ceil(w.length / 2);
    words.splice(i, 1, w.slice(0, h), w.slice(h));
  }
  const len = (i, j) => words.slice(i, j).join(" ").length;
  let best = null, bestMax = Infinity;
  const cut = (start, left, acc) => {
    if (left === 1) { const m = Math.max(...acc.map(([i, j]) => len(i, j)), len(start, words.length)); if (m < bestMax) { bestMax = m; best = [...acc, [start, words.length]]; } return; }
    for (let e = start + 1; e <= words.length - left + 1; e++) cut(e, left - 1, [...acc, [start, e]]);
  };
  cut(0, n, []);
  return best.map(([i, j]) => words.slice(i, j).join(" "));
}

