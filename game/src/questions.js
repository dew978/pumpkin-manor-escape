function nearMiss(ans, r, steps = [1, 2, 10, -1, -2, -10, 3, 5]) {
  const out = new Set();
  for (const s of shuffle(steps.slice(), r)) { const v = ans + s; if (v > 0 && v !== ans) out.add(v); if (out.size >= 3) break; }
  for (let k = 4; out.size < 3; k++) if (ans + k !== ans) out.add(ans + k);
  return [...out];
}
